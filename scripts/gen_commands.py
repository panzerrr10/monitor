def build():
    groups = [
        ("linux", "Linux 命令", "🐧", LINUX + LINUX2),
        ("network", "网络运维", "🌐", NET),
        ("mysql", "MySQL", "🗄️", MYSQL),
        ("docker", "Docker", "🐳", DOCKER),
        ("windows", "Windows", "🪟", WINDOWS),
    ]
    out = {"version": 1, "groups": [], "commands": []}
    for gid, gname, gicon, rows in groups:
        out["groups"].append({"id": gid, "name": gname, "icon": gicon})
        for i, row in enumerate(rows, 1):
            cat, name, cmd, desc, usage, example = row[:6]
            warn = len(row) > 6 and bool(row[6])
            out["commands"].append({
                "id": f"{gid}-{len(out['commands']):04d}",
                "group": gid,
                "cat": cat,
                "name": name,
                "cmd": cmd,
                "desc": desc,
                "usage": usage,
                "example": example,
                "warn": warn,
            })
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print(f"已生成 {OUT}")
    print(f"  分组 {len(out['groups'])} 个，命令 {len(out['commands'])} 条")
    for g in out["groups"]:
        n = sum(1 for c in out["commands"] if c["group"] == g["id"])
        print(f"    {g['icon']} {g['name']}: {n} 条")


if __name__ == "__main__":
    build()
